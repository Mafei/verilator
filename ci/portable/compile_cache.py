"""Reclaim rebuildable compilation caches after explicitly selected drivers finish."""

from contextlib import contextmanager
import os
from pathlib import Path
import re
import stat

DIRECTORY_FLAGS = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
PRESERVED_SCOPE = [
    "original inputs", "generated C++ sources and headers", "model executables", "logs",
    "waveforms", "statistics", "coverage", "archives (.a)", "dependencies (.d)", "audit files",
    "unknown objects and caches", "symbolic links"
]


@contextmanager
def _directory(name, parent=None):
    descriptor = os.open(name, DIRECTORY_FLAGS, dir_fd=parent)
    try:
        yield descriptor
    finally:
        os.close(descriptor)


@contextmanager
def _checkout_directory(root):
    """Open every path component without following a directory symbolic link."""
    if '..' in root.parts:
        raise ValueError("Checkout path must not contain parent components")
    descriptor = os.open(root.anchor, DIRECTORY_FLAGS)
    try:
        for component in root.parts[1:]:
            child = os.open(component, DIRECTORY_FLAGS, dir_fd=descriptor)
            os.close(descriptor)
            descriptor = child
        yield descriptor
    finally:
        os.close(descriptor)


def _regular(directory, name):
    try:
        return stat.S_ISREG(os.stat(name, dir_fd=directory, follow_symlinks=False).st_mode)
    except FileNotFoundError:
        return False


def _header(directory, name):
    if not _regular(directory, name):
        return b''
    descriptor = os.open(name, os.O_RDONLY | os.O_NOFOLLOW, dir_fd=directory)
    with os.fdopen(descriptor, 'rb') as stream:
        return stream.read(4096)


def _generated(directory, name, aggregate=False):
    header = _header(directory, name)
    if aggregate:
        return header.startswith(b'// DESCRIPTION: Generated by verilator_includer via makefile\n')
    return (header.startswith(b'// Verilated -*- C++ -*-\n')
            and b'// DESCRIPTION: Verilator output:' in header)


def _prefixes(directory, filenames):
    prefixes = []
    for name in sorted(filenames):
        if not name.endswith('.mk'):
            continue
        header = _header(directory, name)
        if not header.startswith(b'# Verilated -*- Makefile -*-\n'
                                 b'# DESCRIPTION: Verilator output: Makefile'):
            continue
        match = re.search(rb'^VM_PREFIX = ([A-Za-z_][A-Za-z0-9_]*)\s*$', header, re.MULTILINE)
        if match:
            prefix = match.group(1).decode('ascii')
            if name == prefix + '.mk' and _generated(directory, prefix + '.h'):
                prefixes.append(prefix)
    return prefixes


def _rebuild_source(directory, name, prefixes, runtime):
    for prefix in prefixes:
        if name in (prefix + '__pch.h.fast.gch', prefix + '__pch.h.slow.gch'):
            source = prefix + '__pch.h'
            if _generated(directory, source):
                return source, 'generated_precompiled_header'
        if name.endswith('.o'):
            stem = name[:-2]
            if stem == prefix or stem.startswith(prefix + '__'):
                source = stem + '.cpp'
                if _generated(directory, source, aggregate=stem == prefix + '__ALL'):
                    return source, 'generated_object'
    if (prefixes and re.fullmatch(r'verilated(?:_[A-Za-z0-9_]+)?\.o', name)
            and _regular(runtime, name[:-2] + '.cpp')):
        return 'include/' + name[:-2] + '.cpp', 'runtime_object'
    return None


def _reclaim_driver(directory, runtime, relative, ledger):

    def scan_error(error):
        ledger['status'] = 'infrastructure_failure'
        ledger['failure'] = {'path': str(relative), 'error': str(error)}
        error.compile_cache_ledger = ledger
        raise error

    for folder, directories, filenames, descriptor in os.fwalk('.',
                                                               onerror=scan_error,
                                                               dir_fd=directory,
                                                               follow_symlinks=False):
        local = relative / folder
        for name in sorted(directories + filenames):
            info = os.stat(name, dir_fd=descriptor, follow_symlinks=False)
            if stat.S_ISLNK(info.st_mode):
                ledger['preserved_symlinks'].append(str(local / name))
        directories[:] = sorted(
            name for name in directories
            if not stat.S_ISLNK(os.stat(name, dir_fd=descriptor, follow_symlinks=False).st_mode))
        prefixes = _prefixes(descriptor, filenames)
        for name in sorted(filenames):
            if not name.endswith(('.o', '.gch')) or not _regular(descriptor, name):
                continue
            source = _rebuild_source(descriptor, name, prefixes, runtime)
            path = str(local / name)
            if not source:
                ledger['retained_unknown_caches'].append(path)
                continue
            source_name, kind = source
            info = os.stat(name, dir_fd=descriptor, follow_symlinks=False)
            try:
                os.unlink(name, dir_fd=descriptor)
            except OSError as error:
                ledger['status'] = 'infrastructure_failure'
                ledger['failure'] = {'path': path, 'error': str(error)}
                error.compile_cache_ledger = ledger
                raise
            ledger['removed'].append({
                'path':
                path,
                'bytes':
                info.st_size,
                'kind':
                kind,
                'rebuild_source':
                source_name if kind == 'runtime_object' else str(local / source_name)
            })
            ledger['bytes'] += info.st_size


def reclaim_completed(root, selected):
    """Return a ledger for finished driver names from the explicit regression selection.

    The caller must first wait for all selected drivers and their children to finish.
    Names use the registry spelling without ``t_``; no other driver directories are
    inspected. No makefile or model is executed. OSError propagates; all I/O failures
    carry the partial ledger as ``compile_cache_ledger`` for infrastructure reporting.
    """
    if (not isinstance(selected, (list, tuple)) or not selected
            or any(not isinstance(name, str) or not re.fullmatch(r'[A-Za-z0-9_]+', name)
                   for name in selected) or len(selected) != len(set(selected))):
        raise ValueError("Select distinct completed regression driver names")
    root = Path(root).absolute()
    ledger = {
        'schema': 'completed-compile-cache-v1',
        'status': 'in_progress',
        'root': str(root),
        'selected': list(selected),
        'removed': [],
        'bytes': 0,
        'preserved_scope': list(PRESERVED_SCOPE),
        'preserved_symlinks': [],
        'retained_unknown_caches': [],
        'missing_driver_directories': []
    }
    failure_path = '.'
    try:
        with _checkout_directory(root) as checkout, _directory('include', checkout) as runtime:
            with _directory('test_regress', checkout) as tests:
                try:
                    objects = os.open('obj_vlt', DIRECTORY_FLAGS, dir_fd=tests)
                except FileNotFoundError:
                    ledger['missing_driver_directories'] = list(selected)
                    ledger['status'] = 'complete'
                    return ledger
                try:
                    for name in selected:
                        relative = Path('test_regress/obj_vlt') / ('t_' + name)
                        failure_path = str(relative)
                        try:
                            driver = os.open('t_' + name, DIRECTORY_FLAGS, dir_fd=objects)
                        except FileNotFoundError:
                            ledger['missing_driver_directories'].append(name)
                            continue
                        try:
                            _reclaim_driver(driver, runtime, relative, ledger)
                        finally:
                            os.close(driver)
                finally:
                    os.close(objects)
    except OSError as error:
        ledger['status'] = 'infrastructure_failure'
        ledger.setdefault('failure', {'path': failure_path, 'error': str(error)})
        error.compile_cache_ledger = ledger
        raise
    ledger['status'] = 'complete'
    return ledger
