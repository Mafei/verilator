"""Exercise bounded cache reclamation without a compiler or HDL simulation."""
# pylint: disable=missing-function-docstring

import errno
import json
import os
from pathlib import Path
import tempfile
import unittest
from unittest import mock

import compile_cache

GENERATED = '// Verilated -*- C++ -*-\n// DESCRIPTION: Verilator output: test fixture\n'


class CompileCacheTest(unittest.TestCase):
    """Protect evidence while reclaiming only proven generated compilation caches."""

    def setUp(self):
        temporary = tempfile.TemporaryDirectory()  # pylint: disable=consider-using-with
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name).resolve()
        self.objects = self.root / 'test_regress/obj_vlt'
        self.objects.mkdir(parents=True)
        (self.root / 'include').mkdir()
        self.driver = self.objects / 't_example'
        self.driver.mkdir()
        self.model(self.driver)

    def write(self, path, data):
        path.write_text(data, encoding='utf-8')
        return path

    def model(self, directory, prefix='Vexample'):
        self.write(
            directory / (prefix + '.mk'), '# Verilated -*- Makefile -*-\n'
            '# DESCRIPTION: Verilator output: Makefile for building Verilated archive\n'
            'VM_PREFIX = ' + prefix + '\n')
        for name in (prefix + '.h', prefix + '.cpp', prefix + '__pch.h', prefix + '__main.cpp'):
            self.write(directory / name, GENERATED)

    def test_reclaims_only_proven_rebuildable_files(self):
        removed = [
            'Vexample.o', 'Vexample__main.o', 'Vexample__pch.h.fast.gch',
            'Vexample__pch.h.slow.gch', 'verilated.o', 'verilated_timing.o', 'Vexample__ALL.o'
        ]
        for name in removed:
            self.write(self.driver / name, 'cache bytes')
        self.write(self.root / 'include/verilated.cpp', 'runtime source')
        self.write(self.root / 'include/verilated_timing.cpp', 'runtime source')
        self.write(
            self.driver / 'Vexample__ALL.cpp',
            '// DESCRIPTION: Generated by verilator_includer via makefile\n'
            '#include "Vexample.cpp"\n')
        kept = [
            'Vexample', 'Vexample.exe', 'Vexample__ALL.a', 'Vexample.d', 'vlt_compile.log',
            'vlt_sim.log', 'wave.vcd', 'wave.fst', 'wave.saif', 'Vexample__stats.txt',
            'coverage.dat', 'original.sv', 'audit.json', 'Vexample__pch.h.fast', 'custom.o',
            'custom.cpp', 'verilated_unknown.o', 'Vexample__missing.o'
        ]
        for name in kept:
            self.write(self.driver / name, 'evidence ' + name)
        before = {p.name: p.read_bytes() for p in self.driver.iterdir()}
        ledger = compile_cache.reclaim_completed(self.root, ['example'])
        self.assertEqual(ledger['status'], 'complete')
        self.assertEqual(ledger['selected'], ['example'])
        self.assertEqual({Path(x['path']).name for x in ledger['removed']}, set(removed))
        self.assertEqual(ledger['bytes'], sum(len(before[n]) for n in removed))
        for name, content in before.items():
            if name not in removed:
                self.assertEqual((self.driver / name).read_bytes(), content, name)
        self.assertEqual(len(ledger['retained_unknown_caches']), 3)
        self.assertIn('archives (.a)', ledger['preserved_scope'])
        json.dumps(ledger)

    def test_only_selected_driver_and_real_nested_directories(self):
        self.write(self.driver / 'Vexample.o', 'first cache')
        nested = self.driver / 'four/profile'
        nested.mkdir(parents=True)
        self.model(nested, 'Vnested')
        self.write(nested / 'Vnested.o', 'nested cache')
        other = self.objects / 't_other'
        other.mkdir()
        self.model(other)
        untouched = self.write(other / 'Vexample.o', 'other cache')
        ledger = compile_cache.reclaim_completed(self.root, ['example'])
        self.assertEqual(len(ledger['removed']), 2)
        self.assertTrue(untouched.exists())

    def test_unknown_objects_without_generated_provenance_are_preserved(self):
        self.write(self.driver / 'Vexample__user.cpp', 'user input')
        self.write(self.driver / 'Vexample__user.o', 'user object')
        self.write(self.driver / 'Vexample_other.cpp', GENERATED)
        self.write(self.driver / 'Vexample_other.o', 'other object')
        (self.driver / 'Vexample.mk').unlink()
        self.write(self.driver / 'Vexample.o', 'unidentified object')
        self.assertEqual(compile_cache.reclaim_completed(self.root, ['example'])['removed'], [])
        self.assertTrue((self.driver / 'Vexample__user.o').exists())

    def test_generated_prefix_does_not_authorize_user_or_mismatched_files(self):
        for name in ['Vexample__user', 'Vexample_other']:
            self.write(self.driver / (name + '.cpp'), 'user input')
            self.write(self.driver / (name + '.o'), 'user object')
        self.write(self.driver / 'Vexample__pch.h.extra.gch', 'unrecognized cache')
        self.assertEqual(compile_cache.reclaim_completed(self.root, ['example'])['removed'], [])

    def test_missing_generated_header_or_make_prefix_preserves_cache(self):
        self.write(self.driver / 'Vexample.o', 'cache')
        self.write(
            self.driver / 'Vexample.mk', '# Verilated -*- Makefile -*-\n'
            '# DESCRIPTION: Verilator output: Makefile\nVM_PREFIX = Vdifferent\n')
        self.assertEqual(compile_cache.reclaim_completed(self.root, ['example'])['removed'], [])
        self.model(self.driver)
        (self.driver / 'Vexample.h').unlink()
        self.assertEqual(compile_cache.reclaim_completed(self.root, ['example'])['removed'], [])

    def test_symlink_files_sources_and_nested_directory_are_preserved(self):
        temporary = tempfile.TemporaryDirectory()  # pylint: disable=consider-using-with
        self.addCleanup(temporary.cleanup)
        outside = Path(temporary.name).resolve()
        self.model(outside)
        cache = self.write(outside / 'Vexample.o', 'outside cache')
        (self.driver / 'Vexample.o').symlink_to(cache)
        (self.driver / 'nested-link').symlink_to(outside, target_is_directory=True)
        (self.driver / 'Vexample__pch.h').unlink()
        (self.driver / 'Vexample__pch.h').symlink_to(outside / 'Vexample__pch.h')
        self.write(self.driver / 'Vexample__pch.h.fast.gch', 'cache with symlink source')
        (self.root / 'include/verilated.cpp').symlink_to(outside / 'Vexample.cpp')
        self.write(self.driver / 'verilated.o', 'cache with symlink source')
        ledger = compile_cache.reclaim_completed(self.root, ['example'])
        self.assertEqual(ledger['removed'], [])
        self.assertTrue(cache.exists())
        self.assertTrue((self.driver / 'Vexample.o').is_symlink())
        self.assertEqual(len(ledger['preserved_symlinks']), 3)

    def test_symlink_parent_of_checkout_is_rejected(self):
        (self.root / 'parent-link').symlink_to(self.root, target_is_directory=True)
        with self.assertRaises(OSError):
            compile_cache.reclaim_completed(self.root / 'parent-link/test_regress', ['example'])

    def test_symlink_selected_driver_and_anchor_are_rejected(self):
        (self.objects / 't_link').symlink_to(self.driver, target_is_directory=True)
        with self.assertRaises(OSError):
            compile_cache.reclaim_completed(self.root, ['link'])
        link = self.root / 'checkout-link'
        link.symlink_to(self.root, target_is_directory=True)
        with self.assertRaises(OSError):
            compile_cache.reclaim_completed(link, ['example'])

    def test_symlink_object_root_is_rejected(self):
        self.objects.rename(self.objects.with_name('saved'))
        self.objects.symlink_to(self.objects.with_name('saved'), target_is_directory=True)
        with self.assertRaises(OSError):
            compile_cache.reclaim_completed(self.root, ['example'])

    def test_invalid_selection_does_not_unlink(self):
        self.write(self.driver / 'Vexample.o', 'cache')
        for selected in ([], 'example', ['../outside'], ['example/child'], ['example', 'example'],
                         [None], ['example\n'], ['*']):
            with self.subTest(selected=selected), self.assertRaises(ValueError):
                compile_cache.reclaim_completed(self.root, selected)
        with self.assertRaises(ValueError):
            compile_cache.reclaim_completed(self.root / 'test_regress/..', ['example'])
        self.assertTrue((self.driver / 'Vexample.o').exists())

    def test_missing_output_directory_is_not_a_failure(self):
        ledger = compile_cache.reclaim_completed(self.root, ['missing'])
        self.assertEqual(ledger['missing_driver_directories'], ['missing'])
        self.objects.rename(self.objects.with_name('saved'))
        ledger = compile_cache.reclaim_completed(self.root, ['example'])
        self.assertEqual(ledger['missing_driver_directories'], ['example'])

    def test_unlink_failure_propagates_with_partial_ledger(self):
        self.write(self.driver / 'Vexample.o', 'first cache')
        failed = self.write(self.driver / 'Vexample__main.o', 'second cache')
        real_unlink = os.unlink

        def fail_one(name, **kwargs):
            if name == failed.name:
                raise OSError(errno.ENOSPC, 'injected unlink failure')
            return real_unlink(name, **kwargs)

        with mock.patch.object(compile_cache.os, 'unlink', side_effect=fail_one):
            with self.assertRaises(OSError) as caught:
                compile_cache.reclaim_completed(self.root, ['example'])
        self.assertEqual(caught.exception.errno, errno.ENOSPC)
        ledger = caught.exception.compile_cache_ledger
        self.assertEqual(ledger['status'], 'infrastructure_failure')
        self.assertEqual(len(ledger['removed']), 1)
        self.assertEqual(Path(ledger['failure']['path']).name, failed.name)
        self.assertTrue(failed.exists())

    def test_directory_scan_failure_is_not_a_completed_cleanup(self):
        blocked = self.driver / 'blocked'
        blocked.mkdir()
        self.model(blocked)
        cache = self.write(blocked / 'Vexample.o', 'cache')
        error = OSError(errno.EIO, 'injected directory scan failure')
        real_open = os.open

        def fail_directory(name, *args, **kwargs):
            if name == 'blocked':
                raise error
            return real_open(name, *args, **kwargs)

        with mock.patch.object(compile_cache.os, 'open', side_effect=fail_directory):
            with self.assertRaises(OSError) as caught:
                compile_cache.reclaim_completed(self.root, ['example'])
        self.assertIs(caught.exception, error)
        ledger = caught.exception.compile_cache_ledger
        self.assertEqual(ledger['status'], 'infrastructure_failure')
        self.assertEqual(ledger['removed'], [])
        self.assertEqual(ledger['failure']['path'], 'test_regress/obj_vlt/t_example')
        self.assertTrue(cache.exists())

    def test_later_driver_io_failure_retains_already_reclaimed_ledger(self):
        second = self.objects / 't_second'
        second.mkdir()
        self.model(second, 'Vsecond')
        retained = self.write(second / 'Vsecond.o', 'second cache')
        for operation, target in [('open', 't_second'), ('stat', 'Vsecond.mk'),
                                  ('open', 'Vsecond.mk')]:
            with self.subTest(operation=operation, target=target):
                removed = self.write(self.driver / 'Vexample.o', 'first cache')
                error = OSError(errno.EIO, 'injected later driver I/O failure')
                original = getattr(os, operation)

                def fail_later(name, *args, **kwargs):
                    if name == target:
                        raise error
                    return original(name, *args, **kwargs)

                with mock.patch.object(compile_cache.os, operation, side_effect=fail_later):
                    with self.assertRaises(OSError) as caught:
                        compile_cache.reclaim_completed(self.root, ['example', 'second'])
                self.assertIs(caught.exception, error)
                ledger = caught.exception.compile_cache_ledger
                self.assertEqual(ledger['status'], 'infrastructure_failure')
                self.assertEqual([x['path'] for x in ledger['removed']],
                                 ['test_regress/obj_vlt/t_example/Vexample.o'])
                self.assertEqual(ledger['bytes'], len('first cache'))
                self.assertEqual(ledger['failure']['path'], 'test_regress/obj_vlt/t_second')
                self.assertFalse(removed.exists())
                self.assertTrue(retained.exists())

    def test_repeated_cleanup_is_an_empty_success(self):
        self.write(self.driver / 'Vexample.o', 'cache')
        self.assertEqual(len(compile_cache.reclaim_completed(self.root, ['example'])['removed']),
                         1)
        self.assertEqual(compile_cache.reclaim_completed(self.root, ['example'])['removed'], [])


if __name__ == '__main__':
    unittest.main()
