import vltest_bootstrap

test.scenarios('linter')
# serializeOnly() is JSON mode; there is no distinct serialize-only or XML flag.
base_dir = test.obj_dir
base_v_flags = test.v_flags.copy()
profiles = (('two_state', []), ('json', ['--fourstate', '-Wno-FUTURE', '--json-only']),
            ('hier', ['--fourstate', '-Wno-FUTURE', '--hierarchical'
                      ]), ('savable', ['--fourstate', '-Wno-FUTURE', '--savable', '--no-timing']))
for profile, options in profiles:
    test.obj_dir = base_dir + '/' + profile
    test.mkdir_ok(test.obj_dir)
    test.v_flags = base_v_flags.copy()
    flags = ['--top-module', 't', '--Mdir', test.obj_dir, *options]
    golden = test.golden_filename.replace('.out', '_' + profile + '.out')
    # New golds are generated by the actual compiler, never handwritten.
    if profile == 'json':
        # JSON serialization is an output mode, mutually exclusive with lint-only.
        test.compile(verilator_make_gmake=False,
                     make_top_shell=False,
                     make_main=False,
                     verilator_flags2=flags,
                     fails=True,
                     expect_filename=golden)
    else:
        test.lint(verilator_flags2=flags, fails=True, expect_filename=golden)
test.obj_dir = base_dir
test.v_flags = base_v_flags
test.passes()
